def _fractional_drills():
    from math import gcd
    out = []
    for n in range(1, 65):
        g = gcd(n, 64)
        nn, dd = n // g, 64 // g
        label = f"{nn}/{dd}" if dd != 1 else f"{nn}"
        out.append((label, n / 64.0))
    return out


FRACTIONAL_DRILLS = _fractional_drills()

